func parseSettings(text string, out map[string]string) {
	section := extractSection(text, []string{"Configuration", "Parameter Changes", "Settings", "配置参数"}, 80)
	if section == "" {
		return
	}
	for _, line := range strings.Split(section, "\n") {
		fields := splitTableRow(line)
		if len(fields) < 2 {
			continue
		}
		k := strings.TrimSpace(fields[0])
		v := strings.TrimSpace(fields[1])
		if k == "" {
			continue
		}
		// Don't apply isHeaderRow here — settings rows often have non-numeric
		// values ("off", "L1,L1") that the header heuristic would flag as
		// "all alphabetic, must be header" and incorrectly skip.
		// Watched-settings allowlist is enough filter.
		if isWatchedSetting(k) {
			out[k] = v
		}
	}
}

func isWatchedSetting(k string) bool {
	for _, w := range []string{
		"shared_buffers", "work_mem", "max_process_memory",
		"autovacuum", "wal_writer_delay", "effective_cache_size",
		"track_stmt_stat_level", "instr_unique_sql_count",
		"track_activity_query_size", "log_min_duration_statement",
		"default_statistics_target",
	} {
		if k == w {
			return true
		}
	}
	return false
}
